def read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def write(rel: str, text: str) -> None:
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8", newline="\n")


def replace_once(text: str, old: str, new: str, label: str) -> str:
    if new in text:
        return text
    if old not in text:
        raise RuntimeError(f"Missing replacement anchor for {label}")
    return text.replace(old, new, 1)


def replace_section(text: str, start: str, end: str, replacement: str, label: str) -> str:
    if replacement.strip() in text:
        return text
    start_i = text.find(start)
    end_i = text.find(end, start_i + len(start))
    if start_i < 0 or end_i < 0:
        raise RuntimeError(f"Missing section anchors for {label}")
    return text[:start_i] + replacement.rstrip() + "\n\n" + text[end_i:]


def insert_before_once(text: str, anchor: str, block: str, marker: str) -> str:
    if marker in text:
        return text
    idx = text.find(anchor)
    if idx < 0:
        raise RuntimeError(f"Missing insertion anchor: {anchor}")
    return text[:idx] + block.rstrip() + "\n\n" + text[idx:]


